#!/bin/bash

# ==============================================================================
# Скрипт безопасной установки репозитория BlackArch
# Выполняет проверку GPG-подписи перед запуском.
# ==============================================================================

# Остановить скрипт при любой ошибке
set -e

# Константы
URL_SCRIPT="https://blackarch.org/strap.sh"
URL_SIG="https://blackarch.org/strap.sh.sig"
# Fingerprint ключа Levon 'noptrix' Kayan (создатель BlackArch)
GPG_KEY_ID="4345771566D76038C7FEB43863EC0ADBEA87E4E3"

# 0. Проверка и установка зависимостей
echo ":: Проверка зависимостей..."
# -S: установка
# -y: обновить базы пакетов (чтобы не получить 404 на старых версиях)
# --needed: ставить пакет, только если он не установлен
# --noconfirm: не спрашивать подтверждение (y/n)
sudo pacman -Sy --needed --noconfirm curl gnupg




echo ":: Начало подготовки к установке BlackArch..."

# 1. Создаем безопасную временную директорию
# mktemp -d создает уникальную папку в /tmp с правами только для текущего юзера
WORK_DIR=$(mktemp -d)
echo "-> Создана временная папка: $WORK_DIR"

# 2. Настраиваем ловушку (Trap) для очистки
# Эта команда сработает АВТОМАТИЧЕСКИ при завершении скрипта (успех или ошибка)
trap "rm -rf '$WORK_DIR'; echo '-> Временные файлы удалены.'" EXIT

# 3. Скачиваем скрипт и подпись
echo ":: Скачивание strap.sh и подписи..."
curl -fsSL "$URL_SCRIPT" -o "$WORK_DIR/strap.sh"
curl -fsSL "$URL_SIG"    -o "$WORK_DIR/strap.sh.sig"

# 4. Работа с GPG
echo ":: Проверка цифровой подписи..."

# Импортируем ключ разработчика с keyserver (если его нет)
# Используем || true, чтобы скрипт не падал, если ключ уже есть и "без изменений"
gpg --keyserver keyserver.ubuntu.com --recv-keys "$GPG_KEY_ID" > /dev/null 2>&1 || true

# Проверяем подпись файла
# Если проверка не пройдет, set -e остановит скрипт здесь
if gpg --quiet --verify "$WORK_DIR/strap.sh.sig" "$WORK_DIR/strap.sh"; then
    echo "-> [УСПЕХ] Подпись валидна. Скрипт подлинный."
else
    echo "-> [ОШИБКА] Неверная цифровая подпись! Отмена выполнения."
    exit 1
fi

# 5. Запуск установки
echo ":: Запуск установки (потребуются права sudo)..."
chmod +x "$WORK_DIR/strap.sh"
sudo "$WORK_DIR/strap.sh"

echo ":: Готово! BlackArch репозиторий подключен."
