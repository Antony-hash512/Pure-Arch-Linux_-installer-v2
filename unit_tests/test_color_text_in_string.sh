#!/bin/bash

# Подключаем тестируемую функцию
# Получаем путь к директории текущего скрипта
SCRIPT_DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" && pwd )"
# Подключаем файл с функциями из каталога include родительской директории
source "${SCRIPT_DIR}/../include/main_functions.sh"

# Цвета для вывода тестов
GREEN='\033[0;32m'
RED='\033[0;31m'
NC='\033[0m' # No Color

# Цвет для тестирования функции
TEST_COLOR='\033[0;36m' # Голубой цвет

# Функция для запуска теста
run_test() {
    local test_name="$1"
    local original_string="$2"
    local text_to_color="$3"
    local color_code="$4"
    local expected="$5"
    
    result=$(color_text_in_string "$original_string" "$text_to_color" "$color_code")
    
    # Для визуальной проверки выводим и результат, и ожидаемое значение
    echo -e "Тест: $test_name"
    echo -e "Результат:  $result"
    echo -e "Ожидаемое: $expected"
    
    # Технически, мы не можем напрямую сравнивать строки с кодами цветов из-за особенностей bash
    # Поэтому просто сообщаем о завершении теста, а пользователь может визуально проверить
    echo -e "${GREEN}Тест завершен${NC}"
    echo ""
}

# Тесты для функции color_text_in_string
echo "Тестирование окрашивания текста в строке:"

# Простой тест - окрашивание слова в середине строки
run_test "Простое окрашивание" \
         "Это тестовая строка для проверки" \
         "тестовая" \
         "$TEST_COLOR" \
         "Это ${TEST_COLOR}тестовая${NC} строка для проверки"

# Тест на окрашивание слова в начале строки
run_test "Окрашивание в начале строки" \
         "Первое слово должно быть окрашено" \
         "Первое" \
         "$TEST_COLOR" \
         "${TEST_COLOR}Первое${NC} слово должно быть окрашено"

# Тест на окрашивание слова в конце строки
run_test "Окрашивание в конце строки" \
         "Должно быть окрашено последнее слово" \
         "слово" \
         "$TEST_COLOR" \
         "Должно быть окрашено последнее ${TEST_COLOR}слово${NC}"

# Тест на окрашивание фразы из нескольких слов
run_test "Окрашивание фразы" \
         "Эта фраза из нескольких слов должна быть окрашена целиком" \
         "фраза из нескольких слов" \
         "$TEST_COLOR" \
         "Эта ${TEST_COLOR}фраза из нескольких слов${NC} должна быть окрашена целиком"

# Тест на окрашивание текста, которого нет в строке
run_test "Окрашивание отсутствующего текста" \
         "Этот текст не содержит искомого слова" \
         "несуществующее" \
         "$TEST_COLOR" \
         "Этот текст не содержит искомого слова"

echo -e "\nВсе тесты выполнены." 