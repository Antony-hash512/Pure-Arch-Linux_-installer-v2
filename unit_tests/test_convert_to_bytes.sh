#!/bin/bash

# Заранее вычисленные степени 1024
MB=1048576  # 1024^2
GB=1073741824  # 1024^3
TB=1099511627776  # 1024^4
PB=1125899906842624  # 1024^5
EB=1152921504606846976  # 1024^6
# Подключаем тестируемую функцию
# Получаем путь к директории текущего скрипта
SCRIPT_DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" && pwd )"
# Подключаем файл с функциями из каталога include родительской директории
source "${SCRIPT_DIR}/../include/main_functions.sh"

# Цвета для вывода
GREEN='\033[0;32m'
RED='\033[0;31m'
NC='\033[0m' # No Color

# Функция для запуска теста
run_test() {
    local test_name="$1"
    local input="$2"
    local expected="$3"
    
    result=$(convert_to_bytes "$input")
    
    if [[ "$result" == "$expected" ]]; then
        echo -e "${GREEN}УСПЕХ${NC}: $test_name"
        echo "  Ожидалось: '$expected'"
        echo "  Получено:  '$result'"
    else
        echo -e "${RED}ОШИБКА${NC}: $test_name"
        echo "  Ожидалось: '$expected'"
        echo "  Получено:  '$result'"
    fi
}

# Тесты для различных единиц измерения
echo "Тестирование преобразования размеров в байты:"
run_test "Килобайты" "1K" "1024"
run_test "Мегабайты" "1M" "1048576"
run_test "Гигабайты" "1G" "1073741824"
run_test "Терабайты" "1T" "1099511627776"
run_test "Петабайты" "1P" "1125899906842624"
run_test "Экзабайты" "1E" "1152921504606846976"
run_test "Байты" "1B" "1"

# Тесты для чисел больше 1
echo -e "\nТестирование преобразования больших размеров:"
run_test "10 Килобайт" "10K" "10240"
run_test "50 Мегабайт" "50M" "52428800"
run_test "2 Гигабайта" "2G" "2147483648"

# Тесты для регистра букв
echo -e "\nТестирование различного регистра букв:"
run_test "Нижний регистр - килобайты" "5k" "5120"
run_test "Нижний регистр - мегабайты" "5m" "5242880"
run_test "Нижний регистр - гигабайты" "5g" "5368709120"

echo -e "\nВсе тесты выполнены." 